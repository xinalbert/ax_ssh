#!/usr/bin/env python3
"""Synchronize gettext catalogs and generate static settings-search tables."""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

from translation_catalog import (
    CatalogEntry,
    MessageKey,
    catalog_paths,
    read_catalog,
    render_catalog,
    search_rows,
    source_keys,
)


def synchronize_catalog(path: Path, keys: set[MessageKey]) -> str:
    """Preserve translations/comments; expose new messages as empty entries."""
    existing = read_catalog(path)
    header = existing.get(MessageKey("", ""))
    if header is None:
        raise ValueError(f"{path}: missing PO header")
    entries = [header]
    for key in sorted(keys):
        entries.append(existing.get(key, CatalogEntry(key, {0: ""})))
    return render_catalog(entries)


def rust_string(value: str) -> str:
    """Quote UTF-8 data with Rust escapes, including control characters."""
    escapes = {'"': '\\"', "\\": "\\\\", "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    encoded = "".join(
        escapes.get(character)
        or (f"\\u{{{ord(character):x}}}" if ord(character) < 32 else character)
        for character in value
    )
    return f'"{encoded}"'


def render_search_catalog(root: Path) -> str:
    """Generate indexed locale tables; the application never parses catalogs."""
    rows = search_rows(root)
    lines = [
        "// Generated by scripts/build_translations.py; edit translations/<locale>/LC_MESSAGES/ax_ssh.po instead.",
        "type SearchRow = (&'static str, &'static str, &'static str);",
        "pub(super) const SETTINGS_SEARCH_CATALOG: &[SearchRow] = &[",
    ]
    for row in rows:
        lines.append("(" + ", ".join(rust_string(value) for value in row) + "),")
    lines.append("];")
    locale_tables: list[tuple[str, str]] = []
    for path in catalog_paths(root):
        locale = path.parent.parent.name
        table_name = "SETTINGS_SEARCH_" + re.sub(r"[^a-zA-Z0-9]", "_", locale).upper()
        if any(name == table_name for _, name in locale_tables):
            raise ValueError(f"duplicate Rust table name for locale {locale}")
        entries = read_catalog(path)
        lines.append(f"const {table_name}: &[SearchRow] = &[")
        for row in rows:
            translated: list[str] = []
            for value in row:
                entry = entries.get(MessageKey("settings-search", value))
                if (
                    entry is None
                    or not entry.translations.get(0, "").strip()
                    or entry.fuzzy
                ):
                    raise ValueError(
                        f"{path}: missing reviewed search translation for {value!r}"
                    )
                translated.append(entry.translations[0])
            lines.append(
                "(" + ", ".join(rust_string(value) for value in translated) + "),"
            )
        lines.append("];")
        locale_tables.append((locale, table_name))
    lines.extend(
        [
            "pub(super) fn localized_catalog(locale: &str) -> Option<&'static [SearchRow]> {",
            "match locale {",
        ]
    )
    for locale, table_name in locale_tables:
        lines.append(f"{rust_string(locale)} => Some({table_name}),")
    lines.extend(["_ => None,", "}", "}"])
    result = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input="\n".join(lines) + "\n",
        encoding="utf-8",
        capture_output=True,
        check=True,
    )
    return result.stdout


def write_or_check(path: Path, content: str, check: bool) -> bool:
    """Compare generated output or write it when explicitly synchronizing."""
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return True
    if check:
        print(f"Outdated translation artifact: {path}", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    """Synchronize selected catalogs and the combined search table."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify generated artifacts without writing",
    )
    parser.add_argument(
        "--locale", help="Only synchronize this existing locale's PO file"
    )
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    try:
        keys = source_keys(root)
        paths = catalog_paths(root)
        selected = [
            path
            for path in paths
            if not args.locale or path.parent.parent.name == args.locale
        ]
        if not selected:
            raise ValueError("no matching bundled locale catalogs")
        valid = True
        for path in selected:
            valid = (
                write_or_check(path, synchronize_catalog(path, keys), args.check)
                and valid
            )
        output = root / "src/app/settings_bridge/settings_search_catalog.rs"
        valid = (
            write_or_check(output, render_search_catalog(root), args.check) and valid
        )
        return int(not valid)
    except (OSError, ValueError, SyntaxError, subprocess.CalledProcessError) as error:
        print(f"Translation generation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
