#!/usr/bin/env python3
"""Generate Rust, Slint and bilingual system-name indexes from the icon catalog."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = Path("assets/os-icons/catalog.json")


@dataclass(frozen=True)
class SystemIcon:
    """Represent one canonical name, its recognition aliases and checked-in art."""

    id: str
    name: str
    family: str
    aliases: tuple[str, ...]
    icon: str


def load_catalog(root: Path) -> list[SystemIcon]:
    """Validate names, unique aliases and resource paths before generating files."""
    catalog = json.loads((root / CATALOG_PATH).read_text(encoding="utf-8"))
    if catalog["schema_version"] != 1:
        raise ValueError("unsupported system-icon catalog schema")
    manifest = json.loads(
        (root / "assets/os-icons/manifest.json").read_text(encoding="utf-8")
    )
    assets = {asset["path"] for asset in manifest["assets"]}
    identifiers: set[str] = set()
    alias_owners: dict[str, str] = {}
    icons = []
    for record in catalog["icons"]:
        icon = SystemIcon(**{**record, "aliases": tuple(record["aliases"])})
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", icon.id):
            raise ValueError(f"invalid canonical identifier: {icon.id!r}")
        if icon.id in identifiers:
            raise ValueError(f"duplicate identifier: {icon.id}")
        identifiers.add(icon.id)
        if icon.family not in {"linux", "windows", "macos"}:
            raise ValueError(f"unsupported family for {icon.id}: {icon.family}")
        if not icon.name.strip() or not icon.aliases:
            raise ValueError(f"missing name or aliases for {icon.id}")
        if not icon.icon.startswith(f"{icon.family}/"):
            raise ValueError(f"icon path does not match family for {icon.id}: {icon.icon}")
        if icon.icon not in assets or not (
            root / "assets/os-icons" / icon.icon
        ).is_file():
            raise ValueError(f"unrecorded or missing icon for {icon.id}: {icon.icon}")
        for alias in icon.aliases:
            if not re.fullmatch(r"[a-z0-9]+(?: [a-z0-9]+)*", alias):
                raise ValueError(f"alias must use normalized words: {alias!r}")
            previous = alias_owners.get(alias)
            if previous is not None:
                raise ValueError(f"alias {alias!r} belongs to {previous} and {icon.id}")
            alias_owners[alias] = icon.id
        icons.append(icon)
    if not {"linux", "macos", "windows"}.issubset(identifiers):
        raise ValueError("catalog must include the three platform families")
    return icons


def rust_catalog(icons: list[SystemIcon]) -> str:
    """Generate constants with specific distribution names ahead of family names."""
    lines = ["// Generated by scripts/generate_system_icons.py; edit catalog.json."]
    for constant, group in (
        ("PLATFORM_FAMILIES", [icon for icon in icons if icon.id == icon.family]),
        ("LINUX_DISTRIBUTIONS", [
            icon for icon in icons if icon.family == "linux" and icon.id != icon.family
        ]),
    ):
        group = sorted(
            group, key=lambda icon: (-max(map(len, icon.aliases)), icon.id)
        )
        lines.append(f"pub(super) const {constant}: &[(&str, &[&str])] = &[")
        for icon in group:
            aliases = ", ".join(json.dumps(alias) for alias in icon.aliases)
            lines.append(f"    ({json.dumps(icon.id)}, &[{aliases}]),")
        lines.append("];\n")
    result = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    )
    return result.stdout


def slint_icons(icons: list[SystemIcon]) -> str:
    """Generate one image component shared by sidebar and workspace tabs."""
    lines = [
        '// Generated by scripts/generate_system_icons.py; edit catalog.json.',
        'import { Theme } from "../theme.slint";',
        '',
        'export component SystemPlatformIcon inherits Image {',
        '    in property <string> platform;',
        '    in property <color> glyph-color: Theme.text;',
        '',
        '    image-fit: contain;',
        '    colorize: Theme.system-icons-follow-theme ? root.glyph-color : transparent;',
        '    source:',
    ]
    for icon in sorted(icons, key=lambda icon: icon.id):
        if icon.id != "linux":
            lines.append(
                f'        root.platform == "{icon.id}" ? '
                f'@image-url("../../assets/os-icons/{icon.icon}") :'
            )
    fallback = next(icon for icon in icons if icon.id == "linux")
    lines.extend([
        f'        @image-url("../../assets/os-icons/{fallback.icon}");',
        '}',
        '',
    ])
    return "\n".join(lines)


def domain_catalog(icons: list[SystemIcon]) -> str:
    """Generate domain choices for validated settings and UI selection."""
    lines = [
        "// Generated by scripts/generate_system_icons.py; edit catalog.json.",
        "use super::SystemIconChoice;",
        "pub(super) const SYSTEM_ICONS: &[SystemIconChoice] = &[",
    ]
    for icon in sorted(icons, key=lambda icon: (icon.family, icon.name.casefold())):
        aliases = sorted(set(icon.aliases) | {icon.id.replace("-", " ")})
        lines.append("SystemIconChoice {")
        for field in ("id", "name", "family"):
            lines.append(f"{field}: {json.dumps(getattr(icon, field))},")
        lines.append("aliases: &[" + ", ".join(map(json.dumps, aliases)) + "], },")
    lines.append("];")
    return subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input="\n".join(lines), text=True, capture_output=True, check=True,
    ).stdout


def name_index(icons: list[SystemIcon], chinese: bool) -> str:
    """Generate a searchable name/alias/path table with matching bilingual rules."""
    if chinese:
        lines = [
            '# 系统图标名称索引', '',
            '[English](names.md) · [统一目录](catalog.json) · [资源与许可](README.zh.md)', '',
            '规范标识使用小写字母、数字和连字符；显示名称保留品牌写法。',
            '别名按单词识别，忽略大小写及标点，具体发行版/版本优先于系统家族。',
            '`linux` 是 Tux 兜底；未知非 Linux 系统使用通用服务器/终端符号。',
            '本机 Linux 优先按 os-release 的 ID 识别，不按 ID_LIKE 继承母发行版图标。', '',
            '维护 catalog.json 后，在仓库根目录执行生成及一致性检查：',
        ]
        header = '| 规范标识 | 显示名称 | 家族 | 识别别名 | 图标路径 |'
    else:
        lines = [
            '# System icon name index', '',
            '[中文](names.zh.md) · [Catalog](catalog.json) · [Assets and licenses](README.md)', '',
            'Canonical IDs use lowercase letters, digits and hyphens; display names retain branding.',
            'Aliases match words without case or punctuation; specific distributions/editions precede families.',
            '`linux` is the Tux fallback; unknown non-Linux systems use generic server/terminal glyphs.',
            'Local Linux uses its os-release ID and does not inherit an ID_LIKE parent icon.', '',
            'After editing catalog.json, generate and check from the repository root:',
        ]
        header = '| Canonical ID | Display name | Family | Recognition aliases | Icon path |'
    lines.extend([
        '', '```bash', 'python3 scripts/generate_system_icons.py',
        'python3 scripts/generate_system_icons.py --check', '```', '',
        header, '| --- | --- | --- | --- | --- |',
    ])
    for icon in sorted(icons, key=lambda icon: (icon.family, icon.id)):
        aliases = ', '.join(f'`{alias}`' for alias in icon.aliases)
        lines.append(
            f'| `{icon.id}` | {icon.name} | {icon.family} | {aliases} | '
            f'[{icon.icon}]({icon.icon}) |'
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    """Generate outputs or report stale files without modifying them in check mode."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check generated files without writing")
    args = parser.parse_args()
    try:
        icons = load_catalog(PROJECT_ROOT)
        outputs = {
            "src/app/system_icons/catalog.rs": rust_catalog(icons),
            "src/config/system_icons/catalog.rs": domain_catalog(icons),
            "ui/components/system-platform-icon.slint": slint_icons(icons),
            "assets/os-icons/names.md": name_index(icons, chinese=False),
            "assets/os-icons/names.zh.md": name_index(icons, chinese=True),
        }
        stale = []
        for relative_path, content in outputs.items():
            path = PROJECT_ROOT / relative_path
            existing = path.read_text(encoding="utf-8") if path.exists() else None
            if existing == content:
                continue
            if args.check:
                stale.append(relative_path)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
        if stale:
            print("Stale generated files: " + ", ".join(stale), file=sys.stderr)
            return 1
    except (OSError, ValueError, KeyError, TypeError, subprocess.CalledProcessError) as error:
        print(f"System-icon generation failed: {error}", file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(icons)} system icons and {len(outputs)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
